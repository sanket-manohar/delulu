// Renders pages (block model) to GitHub-flavoured Markdown.

import { SEV_ICON, STATUS_ICON } from './pages.js';
import { SEVERITY_LABEL } from '../analyzers/common.js';
import { REPO_URL } from '../config.js';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, '<br>');

export function blocksToMarkdown(blocks, state = {}, depth = 0) {
  const out = [];
  const ind = '  '.repeat(depth);
  for (const b of blocks) {
    switch (b.type) {
      case 'h1': out.push(`# ${b.text}`); break;
      case 'h2': out.push(`## ${b.text}`); break;
      case 'h3': out.push(`### ${b.text}`); break;
      case 'p': out.push(b.text); break;
      case 'quote': out.push(`> ${b.text}`); break;
      case 'divider': out.push('---'); break;
      case 'callout': out.push(`> ${b.icon} ${b.text}`); break;
      case 'ul': out.push(b.items.map((i) => `${ind}- ${i}`).join('\n')); break;
      case 'ol': out.push(b.items.map((i, n) => `${ind}${n + 1}. ${i}`).join('\n')); break;
      case 'code': out.push(`${b.title ? `**${b.title}**\n\n` : ''}\`\`\`\n${b.text}\n\`\`\``); break;
      case 'todo': {
        const done = b.status === 'pass' || state[b.id];
        const mark = b.status === 'fail' ? ' ❌' : b.status === 'warn' ? ' ⚠️' : b.status === 'pass' ? ' _(auto-verified)_' : '';
        out.push(`${ind}- [${done ? 'x' : ' '}] ${b.text}${mark}${b.note ? ` — ${b.note}` : ''}`);
        break;
      }
      case 'toggle': out.push(`### ${b.title}\n\n${blocksToMarkdown(b.children, state, depth)}`); break;
      case 'table':
        out.push([`| ${b.head.map(cell).join(' | ')} |`, `| ${b.head.map(() => '---').join(' | ')} |`, ...b.rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n'));
        break;
      case 'props': out.push(b.pairs.map(([k, v]) => `- **${k}:** ${v}`).join('\n')); break;
      case 'bars': out.push(b.items.map((i) => `- ${i.label}: ${i.sub}`).join('\n')); break;
      case 'stats': out.push(b.items.map((i) => `**${i.label}:** ${i.value}${i.sub ? ` (${i.sub})` : ''}`).join(' · ')); break;
      case 'tabs': for (const t of b.items) out.push(`#### ${t.label}\n\n${blocksToMarkdown(t.children, state, depth)}`); break;
      case 'timeline': out.push(b.items.map((t) => `- **${t.title}** (${t.when}) ${t.state === 'done' ? '✅' : t.state === 'current' ? '👉' : ''} — ${t.text}`).join('\n')); break;
      case 'issue': {
        const i = b.data;
        const lines = [`### ${SEV_ICON[i.severity]} ${i.title}`, `**${SEVERITY_LABEL[i.severity]}** · ${i.group}${i.itms ? ` · ${i.itms}` : ''}${i.masvs ? ` · ${i.masvs}` : ''}`, '', i.detail];
        if (i.evidence?.length) lines.push('', '**Evidence**', ...i.evidence.map((e) => `- \`${e}\``));
        if (i.fixSteps?.length) lines.push('', '**How to fix**', ...i.fixSteps.map((s, n) => `${n + 1}. ${s}`));
        if (i.refs?.length) lines.push('', i.refs.map((r) => `[${r.label}](${r.url})`).join(' · '));
        out.push(lines.join('\n'));
        break;
      }
      case 'nextstep': out.push(`> **${b.title}** — ${b.text}`); break;
      case 'stepper': out.push(b.steps.map((x) => `${x.state === 'done' ? '✅' : x.state === 'current' ? '👉' : '⬜'} ${x.label}`).join(' → ')); break;
      case 'apptype': case 'fwpicker': break;
      default: break;
    }
  }
  return out.filter(Boolean).join('\n\n');
}

export function pageToMarkdown(page, state) {
  return `# ${page.icon} ${page.title}\n\n${page.subtitle ? `_${page.subtitle}_\n\n` : ''}${blocksToMarkdown(page.blocks, state)}\n\n---\n_Generated by [Delulu](${REPO_URL}) — open-source mobile release readiness checks._\n`;
}

export function checksTable(report) {
  return [`| | Check | Severity | Detail |`, `|---|---|---|---|`, ...report.checks.map((c) => `| ${STATUS_ICON[c.status]} | ${cell(c.title)} | ${c.severity || ''} | ${cell(c.detail.split('. ')[0])} |`)].join('\n');
}
