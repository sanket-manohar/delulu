test('macho: thin + fat headers, build version, PIE', () => {
  const thin = inspectMacho(buildMacho({ minos: '15.1', sdk: '26.0' }));
  assert.equal(thin.cpu, 'arm64');
  assert.equal(thin.platform, 'iOS');
  assert.equal(thin.minos, '15.1');
  assert.equal(thin.sdk, '26.0');
  assert.equal(thin.pie, true);
  const fat = machoSlices(buildFat([{ cpu: 0x0100000c, bytes: buildMacho({}) }, { cpu: 0x01000007, bytes: buildMacho({ cpu: 0x01000007 }) }]));
  assert.deepEqual(fat.map((s) => s.cpu), ['arm64', 'x86_64']);
  assert.ok(compareVersions('26.1', '26') > 0);
  assert.ok(compareVersions('12.4', '13') < 0);
});

test('scanner: finds secrets across chunk boundaries and masks them', () => {
  const s = new ContentScanner({ markers: ['CLLocationManager'] });
  const key = ['sk', 'live', 'abcdefghijklmnopqrstuvwx'].join('_');
  const feed = s.createFeeder('f.bin');
  const text = `junk ${key} more http://api.evil.example/x CLLocationManager`;
  feed(enc.encode(text.slice(0, 12)));
  feed(enc.encode(text.slice(12)));
  const found = s.secretList();
  assert.equal(found.length, 1);
  assert.equal(found[0].id, 'stripe-secret');
  assert.ok(!found[0].masked.includes('mnop'));
  assert.equal(s.httpList()[0].host, 'api.evil.example');
  assert.ok(s.has('CLLocationManager'));
  assert.equal(maskSecret('abc'), 'abc•••');
});

