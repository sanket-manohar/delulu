test('axml: encode → parse round trip with typed values', () => {
  const tree = {
    tag: 'manifest', attrs: { package: 'com.x.y', versionCode: 42, versionName: '1.0' },
    children: [{ tag: 'application', attrs: { debuggable: true, allowBackup: false, label: 'X' }, children: [] }],
  };
  const out = parseAxml(encodeAxml(tree));
  assert.equal(out.tag, 'manifest');
  assert.equal(out.attrs.package, 'com.x.y');
  assert.equal(out.attrs.versionCode, 42);
  assert.equal(out.children[0].attrs.debuggable, true);
  assert.equal(out.children[0].attrs.allowBackup, false);
});

function pb(field, wire, payload) {
  const key = (field << 3) | wire;
  const varint = (n) => { const o = []; do { let b = n & 0x7f; n >>>= 7; if (n) b |= 0x80; o.push(b); } while (n); return o; };
  if (wire === 0) return new Uint8Array([...varint(key), ...varint(payload)]);
  const bytes = typeof payload === 'string' ? enc.encode(payload) : payload;
  return new Uint8Array([...varint(key), ...varint(bytes.length), ...bytes]);
}
const cat = (...a) => { const o = new Uint8Array(a.reduce((n, x) => n + x.length, 0)); let i = 0; for (const x of a) { o.set(x, i); i += x.length; } return o; };

test('protoxml: decodes aapt2 protobuf manifest (AAB)', () => {
  const attr = (name, value) => pb(4, 2, cat(pb(2, 2, name), pb(3, 2, value)));
  const usesSdk = pb(5, 2, pb(1, 2, cat(pb(3, 2, 'uses-sdk'), attr('minSdkVersion', '24'), attr('targetSdkVersion', '36'))));
  const manifest = pb(1, 2, cat(pb(3, 2, 'manifest'), attr('package', 'com.aab.app'), usesSdk));
  const t = parseProtoXml(manifest);
  assert.equal(t.tag, 'manifest');
  assert.equal(t.attrs.package, 'com.aab.app');
  assert.equal(t.children[0].attrs.targetSdkVersion, 36);
});

