const enc = new TextEncoder();

test('zip: stored entries round-trip', async () => {
  const z = await openZip(new Blob([buildZip([{ name: 'a.txt', data: 'hello' }, { name: 'dir/b.bin', data: new Uint8Array([1, 2, 3]) }])]));
  assert.equal(z.files().length, 2);
  assert.equal(await z.readText('a.txt'), 'hello');
  assert.deepEqual([...(await z.read('dir/b.bin'))], [1, 2, 3]);
});

test('zip: deflated entries are inflated (streaming)', async () => {
  // Hand-build a zip with one deflated entry.
  const data = enc.encode('x'.repeat(100000) + 'END');
  const comp = deflateRawSync(data);
  const name = enc.encode('big.txt');
  const lh = new Uint8Array(30 + name.length); const lv = new DataView(lh.buffer);
  lv.setUint32(0, 0x04034b50, true); lv.setUint16(8, 8, true); lv.setUint32(14, crc32(data), true);
  lv.setUint32(18, comp.length, true); lv.setUint32(22, data.length, true); lv.setUint16(26, name.length, true); lh.set(name, 30);
  const ch = new Uint8Array(46 + name.length); const cv = new DataView(ch.buffer);
  cv.setUint32(0, 0x02014b50, true); cv.setUint16(10, 8, true); cv.setUint32(16, crc32(data), true);
  cv.setUint32(20, comp.length, true); cv.setUint32(24, data.length, true); cv.setUint16(28, name.length, true); ch.set(name, 46);
  const eo = new Uint8Array(22); const ev = new DataView(eo.buffer);
  ev.setUint32(0, 0x06054b50, true); ev.setUint16(8, 1, true); ev.setUint16(10, 1, true); ev.setUint32(12, ch.length, true); ev.setUint32(16, lh.length + comp.length, true);
  const z = await openZip(new Blob([lh, comp, ch, eo]));
  const txt = await z.readText('big.txt');
  assert.equal(txt.length, 100003);
  assert.ok(txt.endsWith('END'));
  const head = await z.read('big.txt', { maxBytes: 10 });
  assert.equal(head.length, 10);
});

